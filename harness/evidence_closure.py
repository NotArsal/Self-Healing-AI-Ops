"""Did the diagnosis cite the evidence that actually bears on the class it named?

WHY THIS EXISTS
`Cloud-OpsBench` (arXiv 2603.00468) reports Joint RCA Accuracy of 0.76 beside an
Evidence Closure Rate of 0.38 and concludes that "final-answer correctness alone
substantially overestimates agents' ability to perform evidence-grounded
diagnosis". `TriFleetRCA` (arXiv 2609.23766) found the same gap from the other
side: "one fault was diagnosed correctly and cited incorrectly every trial, a
failure mode accuracy conceals."

This project has its own instance of exactly that - every diagnosis emitting
F06 carried F07's catalogue name, 28 times out of 28 (`REPORT_DRAFT.md` §4.2).
Class accuracy never saw it. So the question here is the citation analogue:
when the model names a class, does it cite the evidence that discriminates that
class, or evidence belonging to a different one?

WHAT IS AND IS NOT CLAIMED
This is an operationalisation of the Evidence Closure idea, not a
reimplementation of Cloud-OpsBench's metric, and the mapping from class to
discriminating evidence is a judgement recorded below rather than something the
artifacts state. Two numbers are reported separately because they answer
different questions:

  own-class citation   cited at least one METRIC OR CONFIG signal that
                       discriminates the class it named. A floor: it looked at
                       the right family.
  cross-class citation cited the discriminating signal of a DIFFERENT class.
                       Not automatically wrong - ruling F01 out by pointing at
                       a healthy error ratio is good reasoning - so this is
                       reported, never scored.
  log citation         cited any `EV-L*` line. Tracked separately because of
                       what the first version of this script got wrong.

A CORRECTION, BECAUSE THE FIRST VERSION PRODUCED A MISLEADING ZERO
`p6-f01-rca.json` named F01 ten times out of ten and scored 0/10 on own-class
citation, which looked exactly like the failure this script hunts. It is not.
That run diagnosed the outage from the LOGS - "EV-L01 shows backend_log = raise
ConnectionError(e, request=request)" - and never cited the error-ratio metric.
A connection error in the log is direct evidence of an endpoint outage; it is
simply not the signal F01's DETECTOR fires on.

So own-class citation here measures citation of metric and config evidence
only, and for F01 a low score may mean the model reasoned from logs instead.
The `log` column exists so that case is visible rather than scored as a defect.
The ID mapping was checked before concluding this: `p6-f01-rca-symmetric.json`,
written a day later by the same model, cites EV-M01 as
`retrieval_top_similarity_p50` in its own reasoning text, matching the mapping
derived from source - so the evidence ID space had not shifted underneath the
older artifact.

THE DENOMINATOR, AND A CORRECTION
Only the `rca_*_live.py` harnesses record `cited`. **The bench artifacts do
not**, so this cannot be computed over the 80 bench injections that carry the
headline accuracy numbers, and the two sets are not comparable. Said plainly
because the first version of this analysis was proposed on the assumption that
the bench carried the field.

Evidence IDs are DERIVED from `rca/evidence.py`, never re-typed: they are
generated by enumeration over `METRIC_QUERIES` and a fixed config-key tuple, so
inserting a metric renumbers every ID after it. A hardcoded table here would
silently describe the wrong signals - the same failure this project has hit
with `kept_chunks`, the corpus fingerprint and the drain threshold.

    python -I harness/evidence_closure.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "apps" / "control-plane")]

from kavach.rca.evidence import METRIC_QUERIES  # noqa: E402

# The config keys `collect()` enumerates, in its order. Imported would be
# better; it is a literal tuple inside the function, so it is mirrored here
# with an assertion below that the two have not drifted apart.
CONFIG_KEYS = ("rerank_threshold", "llm_model", "llm_base_url", "max_tokens",
               "chaos_enabled", "llm_timeout_s")

# Which signal NAMES discriminate which class. Derived from what each detector
# reads, not from what looks related:
#   F01 endpoint_outage   - the error ratio its Thresholds fire on
#   F06 retrieval_collapse- the three grounding signals in its QUERIES
#   F07 prompt_regression - the prompt hashes; it reads no PromQL at all
#   F08 config_regression - the settings comparison and the config hash
DISCRIMINATING: dict[str, tuple[str, ...]] = {
    "F01": ("llm_error_ratio",),
    "F02": ("llm_generation_latency_p95",),
    "F06": ("retrieval_top_similarity_p50", "retrieval_kept_chunks_mean",
            "retrieval_empty_context_ratio"),
    "F07": ("prompt_file_hashes",),
    "F08": ("max_tokens", "config_hash"),
}

# Artifacts that record `cited`, labelled with the configuration each measured.
# NOT pooled: the F07 files are an ablation series over the PromQL frame window
# (ADR 0013) and averaging them would describe a system that never shipped.
SOURCES: list[tuple[str, str, str]] = [
    ("p6-f01-rca.json", "F01", "shipped config"),
    ("p6-f01-rca-symmetric.json", "F01", "symmetric-prompt variant"),
    ("p6-f07-rca.json", "F07", "llama3.2"),
    ("p6-f07-rca-qwen.json", "F07", "qwen, frame [10m] - NOT shipped (ADR 0013)"),
    ("p6-f07-rca-qwen-ctx8192.json", "F07", "qwen, frame [1m], ctx 8192"),
    ("p6-f07-rca-qwen-ctx4096-ab.json", "F07", "qwen, frame [1m], ctx 4096"),
    ("p6-f07-rca-qwen-frame10m-ab.json", "F07", "qwen, frame [10m] A/B"),
    ("p6-f08-rca.json", "F08", "llama3.2"),
    ("p6-f08-rca-qwen.json", "F08", "qwen, shipped config"),
]


def id_for_name() -> dict[str, str]:
    """name -> evidence id, built the way `collect()` builds the ids."""
    out: dict[str, str] = {}
    for n, name in enumerate(METRIC_QUERIES, start=1):
        out[name] = f"EV-M{n:02d}"
    for n, key in enumerate(CONFIG_KEYS, start=1):
        out[key] = f"EV-C{n:02d}"
    out["config_hash"] = "EV-C07"
    out["prompt_file_hashes"] = "EV-C08"
    return out


def main() -> int:
    names = id_for_name()

    # The mirrored tuple must still match the module, or every EV-C id below
    # is describing a different setting than the one the model was shown.
    src = (ROOT / "apps/control-plane/kavach/rca/evidence.py").read_text(
        encoding="utf-8")
    for key in CONFIG_KEYS:
        assert f'"{key}"' in src, (
            f"config key {key!r} is no longer in rca/evidence.py; the EV-C "
            f"numbering here is stale")
    assert names["llm_error_ratio"].startswith("EV-M"), "metric ids broke"

    want = {cls: {names[n] for n in sigs if n in names}
            for cls, sigs in DISCRIMINATING.items()}
    print("discriminating evidence, derived from source:")
    for cls in sorted(want):
        print(f"  {cls}  {sorted(want[cls])}")
    print()

    hdr = (f"{'artifact':44} {'inj':>3} {'n':>3} {'named':>5} "
           f"{'own':>6} {'cross':>6} {'log':>5}")
    print(hdr)
    print("-" * len(hdr))

    totals = {"n": 0, "named": 0, "own": 0, "cross": 0, "log": 0}
    for fname, injected, label in SOURCES:
        path = ROOT / "harness" / "reports" / fname
        if not path.is_file():
            print(f"  {fname:44} MISSING")
            continue
        doc: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
        rows = [r for r in doc.get("runs", []) if r.get("cited")]
        if not rows:
            print(f"  {fname:44} no cited field")
            continue

        named = own = cross = logs = 0
        for r in rows:
            cls = str(r.get("fault_class") or "")
            cited = set(r.get("cited") or [])
            if cls == injected:
                named += 1
            mine = want.get(cls, set())
            if mine & cited:
                own += 1
            others: set[str] = set()
            for other, ids in want.items():
                if other != cls:
                    others |= ids
            if (others - mine) & cited:
                cross += 1
            if any(e.startswith("EV-L") for e in cited):
                logs += 1

        n = len(rows)
        print(f"  {fname:44} {injected:>3} {n:>3} {named:>5} "
              f"{own:>4}/{n:<2} {cross:>4}/{n:<2} {logs:>3}/{n:<2}  {label}")
        for k, v in (("n", n), ("named", named), ("own", own),
                     ("cross", cross), ("log", logs)):
            totals[k] += v

    print()
    n = totals["n"]
    if n:
        print(f"  pooled over {n} diagnoses that recorded citations:")
        print(f"    named the injected class      "
              f"{totals['named']}/{n} = {totals['named'] / n:.0%}")
        print(f"    cited own-class evidence      "
              f"{totals['own']}/{n} = {totals['own'] / n:.0%}")
        print(f"    also cited another class's    "
              f"{totals['cross']}/{n} = {totals['cross'] / n:.0%}")
        print(f"    cited log evidence            "
              f"{totals['log']}/{n} = {totals['log'] / n:.0%}")
        print()
        print("  Pooling is for scale only - these artifacts span two models")
        print("  and an ablation series over the PromQL frame window, so the")
        print("  per-file rows above are the comparable numbers.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
